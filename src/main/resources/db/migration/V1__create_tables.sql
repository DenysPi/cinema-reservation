CREATE TABLE movies (
    movie_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255) NOT NULL,
    duration    INTEGER      NOT NULL CHECK (duration > 0)
);

CREATE TABLE halls (
    hall_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255) NOT NULL,
    row_count      INTEGER      NOT NULL CHECK (row_count > 0),
    seats_per_row  INTEGER      NOT NULL CHECK (seats_per_row > 0)
);

CREATE TABLE users (
    user_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(255) NOT NULL
);

CREATE TABLE seats (
    seat_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hall_id      BIGINT       NOT NULL,
    row_label    VARCHAR(255) NOT NULL,
    seat_number  INTEGER      NOT NULL,
    CONSTRAINT fk_seats_hall FOREIGN KEY (hall_id) REFERENCES halls (hall_id),
    CONSTRAINT uk_seats_hall_row_number UNIQUE (hall_id, row_label, seat_number)
);

CREATE TABLE screenings (
    screening_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id      BIGINT       NOT NULL,
    hall_id       BIGINT       NOT NULL,
    start_time    TIMESTAMP(6) NOT NULL,
    price         INTEGER      NOT NULL CHECK (price >= 0),
    CONSTRAINT fk_screenings_movie FOREIGN KEY (movie_id) REFERENCES movies (movie_id),
    CONSTRAINT fk_screenings_hall  FOREIGN KEY (hall_id)  REFERENCES halls (hall_id)
);

CREATE TABLE bookings (
    booking_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL,
    screening_id  BIGINT       NOT NULL,
    reference     VARCHAR(255) NOT NULL,
    status        VARCHAR(255) NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    expires_at    TIMESTAMP(6),
    CONSTRAINT fk_bookings_user      FOREIGN KEY (user_id)      REFERENCES users (user_id),
    CONSTRAINT fk_bookings_screening FOREIGN KEY (screening_id) REFERENCES screenings (screening_id),
    CONSTRAINT uk_bookings_reference UNIQUE (reference),
    CONSTRAINT ck_bookings_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED'))
);

CREATE TABLE booking_seats (
    booking_seat_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id       BIGINT NOT NULL,
    screening_id     BIGINT NOT NULL,
    seat_id          BIGINT NOT NULL,
    CONSTRAINT fk_booking_seats_booking   FOREIGN KEY (booking_id)   REFERENCES bookings (booking_id),
    CONSTRAINT fk_booking_seats_screening FOREIGN KEY (screening_id) REFERENCES screenings (screening_id),
    CONSTRAINT fk_booking_seats_seat      FOREIGN KEY (seat_id)      REFERENCES seats (seat_id),
    CONSTRAINT uk_booking_seat_screening_seat UNIQUE (screening_id, seat_id)
);


CREATE INDEX idx_screenings_movie_start ON screenings (movie_id, start_time);
CREATE INDEX idx_screenings_hall        ON screenings (hall_id);
CREATE INDEX idx_bookings_user          ON bookings (user_id);
CREATE INDEX idx_booking_seats_booking  ON booking_seats (booking_id);